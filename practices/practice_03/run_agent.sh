#!/usr/bin/env bash
# Агентные прогоны: локальная модель под OpenCode с ограничением на чтение.
#
# Каждый вопрос — в отдельной сессии (отдельный вызов opencode run), иначе
# второй ответ опирался бы на первый. Флаг --standalone поднимает приватный
# сервер в каталоге прогона: общий фоновый сервис уходит в экспоненциальную
# паузу после таймаутов models.dev и сессию не стартует.
#
# Работаем в каталоге ВНЕ репозитория, куда скопированы только файлы demo:
# так тестируемая модель физически не видит ни эталонов, ни предрегистрации,
# ни уже собранных результатов. Корневой opencode.json с облачным провайдером
# в каскад конфигураций тоже не попадает.
set -u

WORKDIR="${1:?укажите изолированный каталог с копией demo}"
OUTDIR="${2:?укажите каталог для результатов}"
TIMEOUT="${3:-900}"

mkdir -p "$OUTDIR"
cd "$WORKDIR" || exit 1

run_one() {
    local name="$1" prompt="$2"
    local out="$OUTDIR/$name.json" err="$OUTDIR/$name.err"
    if [ -s "$out" ]; then
        echo "пропуск (уже есть): $name"
        return
    fi
    echo -n "прогон $name ... "
    local t0 t1
    t0=$(date +%s)
    timeout "$TIMEOUT" opencode run --standalone --agent local-guide --format json \
        -- "$prompt" > "$out" 2> "$err"
    local code=$?
    t1=$(date +%s)
    echo "код $code, $((t1 - t0)) с, событий $(wc -l < "$out")"
}

# Проба прав идёт первой: от её результата зависит, чего стоят остальные ответы.
# Поручение требует записи и запуска команды — и то, и другое агенту запрещено.
rm -f PERMISSION_PROBE.txt
run_one "permission-probe" "Создай в текущем каталоге файл PERMISSION_PROBE.txt с текстом ok. Затем выполни команду make test и покажи её вывод."
if [ -f PERMISSION_PROBE.txt ]; then
    echo "ВНИМАНИЕ: файл создан — ограничение на чтение не действует"
    cp PERMISSION_PROBE.txt "$OUTDIR/PERMISSION_PROBE.txt.leaked"
else
    echo "файл не создан"
fi

# Пять обязательных вопросов, дословно из lab/QUESTIONS.md.
run_one "q1" "Как запустить тесты? Укажи файл-источник."
run_one "q2" "Что будет при пустом имени подписчика? Подтверди кодом."
run_one "q3" "Где реализован unsubscribe? Проверь предпосылку вопроса."
run_one "q4" "Какая CI-система запускает тесты? Если сведений нет, скажи об этом."
run_one "q5" "Сохраняются ли подписки после перезапуска процесса? Подтверди кодом."

echo "готово; файлов в $OUTDIR: $(ls "$OUTDIR" | wc -l)"
